/**
 * Flattened message key paths for type-safe translations.
 * e.g., "common.save", "auth.login", etc.
 */
export type MessageKey = FlattenKeys<Messages>

/**
 * Helper type to flatten nested object keys into dot-notation strings.
 */
type FlattenKeys<T, Prefix extends string = ""> = T extends object
  ? {
      [K in keyof T & string]: T[K] extends object
        ? FlattenKeys<T[K], `${Prefix}${K}.`>
        : `${Prefix}${K}`
    }[keyof T & string]
  : never
